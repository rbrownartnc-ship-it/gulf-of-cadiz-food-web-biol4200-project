# ---------------------------------------------------------------- 05 node removal
ko = read("cadiz_node_knockouts.csv")
gu = read("cadiz_guild_removal.csv")
ns = read("cadiz_node_robustness_summary.csv")
nf = read("cadiz_node_fragmentation.csv")
hit = ko[(ko.secondary_topological > 0) | (ko.secondary_weighted > 0)]
r50 = ns.pivot(index="order", columns="rule", values="R50")
rules = ["all prey lost", "3/4 of diet lost", "half of diet lost", "1/4 of diet lost"]
orders = ["random"] + [o for o in ns.order.unique() if o != "random"]
rnd = ns[ns.order == "random"].set_index("rule")
def frag_rows(df):
    out = []
    for r in df.itertuples():
        v = f(r.first_split) if not pd.isna(r.first_split) else "never"
        if r.order == "random":
            v += f" (95%: {f(r.random_lo)}–{f(r.random_hi)})"
        out.append((r.rule, r.order, v))
    return out
write("05_node_removal.md", "Removing groups (nodes)", """
## What was done
- **Extinction rule:** after a removal, a consumer starves once it has lost at least θ of its (rescaled) diet; cannibalism never keeps a group alive.
  - θ = 1 is "all prey lost", the topological rule of Dunne et al. (2002).
  - θ = 0.5 is "half of diet lost", the weighted rule.
  - θ = 0.75 and 0.25 are run as a sensitivity check.
  - Phytoplankton, Detritus and Discard have no prey, so they never starve.
- **Single knockouts:** each of the 43 groups removed on its own.
- **Guild removals:** a whole trophic band or taxonomic group removed at once.
- **Removal sequences:** living groups removed one at a time.
  - Orders: random (×1000), or ranked on the intact web by degree, trophic level, importance as prey, PageRank importance and betweenness.
  - Two recalculated attacks re-rank the targets on the surviving web after every removal (Holme et al. 2002).
  - R50 = fraction of the 41 living groups that must be removed before half of them are lost. Its maximum is 21/41 = 0.51, reached when there are no secondary extinctions.
- **Giant component:** the largest connected part of the web, tracked through the same sequences, with and without secondary extinctions.

## Single knockouts ([`cadiz_node_knockouts.csv`](../output/cadiz_node_knockouts.csv))
""" + f"- Only {len(hit)} of 43 groups cause any secondary extinction when removed alone:\n\n" + table(
    [(r.group, r.secondary_topological, r.secondary_weighted) for r in hit.itertuples()],
    ["group removed", "lost, all-prey rule", "lost, half-diet rule"]) + f"""

- Removing {ko.loc[ko.lscc_after_no_cascade.idxmin(), 'group']} cuts the largest feeding loop from {f(int(G_('largest strongly connected component')))} groups to {int(ko.lscc_after_no_cascade.min())}.
- No single removal splits the web: the largest connected component is always all {int(ko.lwcc_after_no_cascade.min())} remaining groups.

## Guild removals ([`cadiz_guild_removal.csv`](../output/cadiz_guild_removal.csv))
""" + table([(r.guild, r.n_removed, r.secondary_topological, r.secondary_weighted,
              f"{r.living_left_topological} / {r.living_left_weighted}") for r in gu.itertuples()],
            ["guild removed", "groups", "lost, all-prey", "lost, half-diet", "living left (of 41), all-prey / half-diet"]) + """

- Removing predators (upper consumers, top predators, marine mammals/birds/turtles) never causes an extinction. The rule only works bottom-up, so it cannot show predator release.

## R50 by removal order ([`cadiz_node_robustness_summary.csv`](../output/cadiz_node_robustness_summary.csv))
Lower R50 = the web collapses after fewer removals.

""" + table([(o,) + tuple(f(r50.at[o, r]) for r in rules) for o in orders],
            ["order"] + [f"R50, {r}" for r in rules]) + "\n\n" + "\n".join(
    f"- Random orders, {r}: 95% of R50 values fall between {f(rnd.at[r, 'random_R50_lo'])} and {f(rnd.at[r, 'random_R50_hi'])}."
    for r in rules) + """

## When does the surviving web split? ([`cadiz_node_fragmentation.csv`](../output/cadiz_node_fragmentation.csv))
Values are the fraction of living groups removed when the surviving groups first stop forming one connected web. Random = median of 1000 orders.

""" + table(frag_rows(nf), ["rule", "order", "first split"]) + """

## Caveats
- The rule is bottom-up only: consumers starve, but no prey ever explodes when its predator goes. A dynamic model (Landry's equilibrium suggestion) is needed for top-down effects.
- No prey switching: a consumer cannot replace lost prey.
- Removal orders are ranked once on the intact web, except the two recalculated attacks.
- The choice of θ changes how fragile the web looks. The sensitivity table shows which conclusions survive every θ.

## Figures
""" + figlist("05_node_removal"))

# ---------------------------------------------------------------- 06 edge removal
ls_ = read("cadiz_link_robustness_summary.csv")
lf = read("cadiz_link_fragmentation.csv")
l50 = ls_.pivot(index="order", columns="rule", values="L50")
lorders = ["random"] + [o for o in ls_.order.unique() if o != "random"]
lrnd = ls_[ls_.order == "random"].set_index("rule")
crit = lk[(lk.secondary_topological > 0) | (lk.secondary_weighted > 0)]
from scipy.stats import spearmanr
rho, pv = spearmanr(lk.edge_betweenness, lk.diet_share)
write("06_edge_removal.md", "Cutting feeding links (edges)", f"""
## What was done
- A cut link is a feeding interaction that stops: the predator no longer eats that prey, while both groups survive the cut itself.
- The same extinction rules as group removal then apply (θ = 1, 0.75, 0.5, 0.25). Cannibalistic self-loops are left alone.
- **Single-link knockouts:** each of the {len(lk)} feeding links cut on its own. Each link also gets its edge betweenness, and is checked for being a bridge (a link whose loss splits the web).
- **Link-removal sequences:** links cut one at a time.
  - Orders: random (×500), strongest first, weakest first, highest edge betweenness first (static and recalculated; Girvan & Newman 2002, Holme et al. 2002), links from the lowest-trophic-level prey first (bottom-up), and links into the highest-trophic-level predators first (top-down).
  - Links already gone because one end starved are skipped.
  - L50 = fraction of the {len(lk)} links cut before half of the 41 living groups are lost.
- **Giant component:** tracked while links are cut, with and without starvation (bond percolation).

## Single links ([`cadiz_link_knockouts.csv`](../output/cadiz_link_knockouts.csv))
- Links whose loss alone causes an extinction: {int((lk.secondary_topological > 0).sum())} under the all-prey rule, {int((lk.secondary_weighted > 0).sum())} under the half-diet rule.
- Bridges: {int(lk.bridge.sum())}. No single link splits the web.

""" + table([(f"{r.prey} → {r.predator}", f(r.diet_share), r.secondary_topological, r.secondary_weighted)
             for r in crit.itertuples()], ["link (prey → predator)", "diet share", "lost, all-prey", "lost, half-diet"]) + f"""

- Highest edge betweenness: """ + "; ".join(f"{r.prey} → {r.predator} ({r.edge_betweenness:.3f})"
                                            for r in lk.nlargest(5, "edge_betweenness").itertuples()) + f""".
- Edge betweenness against link strength: Spearman ρ = {f(rho)} (p = {pv:.2g}): a weak negative relation, so links on many shortest paths are, on average, slightly weaker links.

## L50 by cutting order ([`cadiz_link_robustness_summary.csv`](../output/cadiz_link_robustness_summary.csv))
Lower L50 = the web collapses after fewer cuts.

""" + table([(o,) + tuple(f(l50.at[o, r]) for r in rules) for o in lorders],
            ["order"] + [f"L50, {r}" for r in rules]) + "\n\n" + "\n".join(
    f"- Random orders, {r}: 95% of L50 values fall between {f(lrnd.at[r, 'random_L50_lo'])} and {f(lrnd.at[r, 'random_L50_hi'])}."
    for r in rules) + """

## When does the surviving web split? ([`cadiz_link_fragmentation.csv`](../output/cadiz_link_fragmentation.csv))
Values are the fraction of links cut when the surviving web first stops being one connected piece. A single group left with no links counts as a split. Random = median, measured every 10 cuts.

""" + table(frag_rows(lf), ["rule", "order", "first split"]) + """

## Caveats
- Diets are fixed: a predator cannot shift effort to its remaining prey (Kondoh 2003 adaptive foraging is the dynamic alternative).
- Strongest and weakest are measured as the share of the predator's diet, which is not the amount of biomass flowing through the link.
- Recalculated edge betweenness is computed on the surviving web after each cut; all other orders are ranked once on the intact web.

## Figures
""" + figlist("06_edge_removal"))

