def f(x, d=2):
    """Format a number for the notes."""
    if isinstance(x, (int, np.integer)):
        return str(int(x))
    if pd.isna(x):
        return "n/a"
    return f"{x:.{d}f}".replace("-", "−")

def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)

def figlist(folder):
    files = sorted((FIG / folder).glob("*.png"))
    return "\n".join(f"- [`{p.stem}`](../figures/{folder}/{p.name})" for p in files)

def write(name, title, body):
    (NOTES / name).write_text(f"# {title}\n\n{HEADER}\n{body.strip()}\n")

